export function t(key: string, substitutions?: string | string[]): string {
  const api = typeof chrome !== 'undefined' ? chrome : undefined;
  const localized = api?.i18n?.getMessage(key, substitutions);
  if (localized) return localized;
  const fallback = FALLBACK_MESSAGES[key] ?? key;
  const values = Array.isArray(substitutions) ? substitutions : substitutions === undefined ? [] : [substitutions];
  return values.reduce((message, value, index) => message.replaceAll(`$${index + 1}`, value), fallback);
}

export function localeTag(): string {
  const api = typeof chrome !== 'undefined' ? chrome : undefined;
  const locale = api?.i18n?.getMessage('@@ui_locale') ?? 'en';
  if (locale === 'zh_TW' || locale.toLowerCase().startsWith('zh-tw')) return 'zh-TW';
  if (locale.toLowerCase().startsWith('zh')) return 'zh-CN';
  if (locale.toLowerCase().startsWith('ja')) return 'ja-JP';
  if (locale.toLowerCase().startsWith('ko')) return 'ko-KR';
  if (locale.toLowerCase().startsWith('pt')) return 'pt-BR';
  if (locale.toLowerCase().startsWith('es_419') || locale.toLowerCase().startsWith('es-419')) return 'es-419';
  if (locale.toLowerCase().startsWith('es')) return 'es-ES';
  if (locale.toLowerCase().startsWith('de')) return 'de-DE';
  if (locale.toLowerCase().startsWith('fr')) return 'fr-FR';
  return 'en-US';
}

export function formatDate(value: string): string {
  const parsed = new Date(value);
  if (Number.isNaN(parsed.valueOf())) return value;
  return new Intl.DateTimeFormat(localeTag(), { year: 'numeric', month: 'short', day: 'numeric' }).format(parsed);
}

export function setDocumentLocale(): void {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = localeTag();
    document.title = t('extName');
  }
}
